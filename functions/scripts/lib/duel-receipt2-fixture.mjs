// duel-receipt-2 fixture builder (fight-host-1). Deterministic: a fixed issue (seed, combatants), a client log made by the
// TS recorder, and the receipt the host computes from them. `node scripts/gen-duel-receipt2-fixture.mjs` rewrites
// Schemas/fixtures/duel-receipt-2.fixture.json; test-duel-receipt2-contract.mjs requires the file to be current.
import { issueFor, recordFightLog, smartPlayer, combatant, verifyFightReplay, clone } from './fight-replay-helpers.mjs';

export function buildReceipt2Fixture() {
  const battleId = 'rb_receipt2fixture0000000001';
  const issue = issueFor({ battleId, seed: 'c0ffee00'.repeat(8), tier: 4,
    player: [combatant('ace', 480, 90, 45), combatant('kuma', 520, 80, 60, 312)], opponent: [combatant('wolf', 450, 85, 40), combatant('gama', 430, 80, 45)] });
  const { wire } = recordFightLog(issue, smartPlayer(issue, 'ace', 'Legendary'));
  const receipt = verifyFightReplay(issue, wire, { battleId }).receipt;
  const mut = (name, f) => { const r = clone(receipt); f(r); return { name, receipt: r }; };
  const invalid = [
    mut('receipt-1-version', r => { r.schemaVersion = 'duel-receipt-1'; }),
    mut('unverified', r => { r.verified = false; }),
    mut('client-verdict-field', r => { r.didWin = true; }),
    mut('winner-side-index', r => { r.winner = 0; }),
    mut('reason-round-limit', r => { r.reason = 'round_limit'; }),
    mut('player-side-1', r => { r.playerSide = 1; }),
    mut('seed-upper', r => { r.seed = r.seed.toUpperCase(); }),
    mut('hp-fraction', r => { r.playerFinal[0].currentHealth = 10.5; }),
    mut('hp-negative', r => { r.playerFinal[0].currentHealth = -1; }),
    mut('four-fighters', r => { r.playerFinal.push(...r.playerFinal.slice(0, 2)); }),
    mut('hashes-odd', r => { r.checkpoints.hashes += 'a'; }),
    mut('histogram-7-bins', r => { r.witness.exchangeHistogram1s.pop(); }),
    mut('witness-label', r => { r.witness.verdict = 'reads as MMA'; }),
    mut('battle-id-prefix', r => { r.battleId = 'pvp_1'; }),
  ];
  return {
    provenance: 'fight-host-1 (HolobotsMobile): generated by functions/scripts/gen-duel-receipt2-fixture.mjs from the TS duel-sim-3 twin (parity-pinned to HolobotsUnity fight-tune-1 0bae2cc16). issue = the rival input-log duel block; log = a client duel-inputs-2 log for it; valid[0] = the receipt the host computes from them (re-derived by the contract test).',
    schemaVersion: 'duel-receipt-2', issue, log: wire, valid: [{ name: 'ace-kuma-vs-wolf-gama-tier4', receipt }], invalid,
  };
}
