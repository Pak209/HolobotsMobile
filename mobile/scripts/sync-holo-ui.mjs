#!/usr/bin/env node
/** Run from any directory: node mobile/scripts/sync-holo-ui.mjs /path/to/HolobotsUnity */
import { copyFile, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
const mobile = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const unity = resolve(process.argv[2] || '../HolobotsUnity');
const relativeSource = 'Assets/UI/Resources/HoloUI';
const source = resolve(unity, relativeSource);
const destination = resolve(mobile, 'assets/items');
await mkdir(destination, { recursive: true });
const files = (await readdir(resolve(source, 'Items'))).filter(name => name.endsWith('.png')).sort();
if (!files.length) throw new Error('No Unity item icons found');
const records = [];
for (const file of files) {
  const bytes = await readFile(resolve(source, 'Items', file));
  await copyFile(resolve(source, 'Items', file), resolve(destination, file));
  records.push({ id: file.slice(0, -4), file, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') });
}
await writeFile(resolve(destination, 'index.ts'), `// Generated by scripts/sync-holo-ui.mjs. Do not hand-edit.\nexport const itemIcons = {\n${records.map(({id,file}) => `  ${JSON.stringify(id)}: require(${JSON.stringify('./'+file)}),`).join('\n')}\n} as const;\n\nexport type ItemIconId = keyof typeof itemIcons;\nexport const ITEM_ICON_COUNT = ${records.length};\n`);
const sourceRepository = execFileSync('git', ['-C', unity, 'remote', 'get-url', 'origin'], { encoding: 'utf8' }).trim();
const sourceCommit = execFileSync('git', ['-C', unity, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
await writeFile(resolve(destination, 'manifest.json'), JSON.stringify({ sourceRepository, sourceCommit, sourcePath: `${relativeSource}/Items`, requestedCount: 92, actualCount: records.length, totalBytes: records.reduce((sum,r)=>sum+r.bytes,0), note: 'The current tracked Unity source contains 105 distinct item, part and clothing filenames; all are preserved, including additions beyond the requested 92.', icons: records }, null, 2)+'\n');
await mkdir(resolve(mobile, 'assets/fonts'), { recursive: true });
for (const file of ['Rajdhani-Medium.ttf', 'Rajdhani-OFL.txt', 'Saira-Regular.ttf', 'Saira-OFL.txt']) await copyFile(resolve(source, file), resolve(mobile, 'assets/fonts', file));
console.log(`Copied ${records.length} icons (${records.reduce((s,r)=>s+r.bytes,0)} bytes) from ${sourceCommit}; generated index, hashes and font licenses.`);
