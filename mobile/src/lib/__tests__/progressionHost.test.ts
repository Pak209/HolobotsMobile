describe("refusals: every host code maps to honest City copy", () => {
  it("each TimerErrorCode the host can send has its own line, for every action; none says host", () => {
    for (const [code, refusal] of Object.entries(fixture.refusals)) {
      expect(refusal!.details).toEqual({ rejectionCode: code });
      expect(PROGRESSION_REFUSAL_COPY[code]).toBeTruthy();
      for (const action of ACTIONS) {
        const copy = progressionRefusalCopy(sdkError(refusal!), action);
        expect(copy.body).toBe(PROGRESSION_REFUSAL_COPY[code]);
        expect(copy.outcome).toBe(code === "not_started_on_host" ? "legacy_refused" : "refused");
        expect(`${copy.title} ${copy.body}`).not.toMatch(/\bhost\b/i);
      }
    }
    expect(Object.keys(fixture.refusals).sort()).toEqual([
      "holobot_busy", "invalid_request", "not_active", "not_complete", "not_enough_energy", "not_started_on_host", "quest_slots_full",
      "request_conflict", "training_active", "unavailable", "unknown_course", "unknown_holobot", "unknown_quest",
    ]);
  });

  it("the recorded claim / start refusals map as the screens need", () => {
    expect(progressionRefusalCopy(sdkError(fixture.claims.cityQuestBeforeEnd!), "quest_claim")).toMatchObject({ body: "Not finished yet by the City's clock.", outcome: "refused" });
    expect(progressionRefusalCopy(sdkError(fixture.starts.holobotBusy!), "quest_start").outcome).toBe("refused");
    expect(progressionRefusalCopy(sdkError(fixture.starts.trainingActive!), "training_start").body).toBe(PROGRESSION_REFUSAL_COPY.training_active);
  });

  it("no reply (transport) is an UNKNOWN outcome, kept for an identical retry; a host 'unavailable' rejection is a definite answer", () => {
    for (const error of [new Error("network"), { code: "functions/unavailable" }, { code: "functions/deadline-exceeded" }, { code: "functions/internal" }, new Error("progression_reply_invalid")]) {
      const copy = progressionRefusalCopy(error, "quest_start");
      expect(copy.outcome).toBe("unknown");
      expect(copy.body).not.toMatch(/\bhost\b/i);
    }
    expect(progressionRefusalCopy(sdkError(fixture.refusals.unavailable!), "quest_start").outcome).toBe("refused");
    // A callable this build can't find (the City not deployed yet) is honest about it, and never a raw code.
    expect(progressionRefusalCopy({ code: "functions/not-found", message: "NOT_FOUND" }, "quest_start")).toMatchObject({ body: PROGRESSION_REFUSAL_COPY["not-found"], outcome: "refused" });
    expect(progressionRefusalCopy({ code: "functions/permission-denied" }, "quest_start").body).toBe("The City refused that. Try again later.");
  });

  it("an unknown outcome keeps the request id (identical retry); a definite answer releases it", () => {
    const memo = createStartRequestMemo();
    const first = memo.requestIdFor("quest:forest_patrol:ACE");
    expect(first).toMatch(PROGRESSION_REQUEST_ID);
    expect(memo.requestIdFor("quest:forest_patrol:ACE")).toBe(first);
    expect(memo.requestIdFor("quest:forest_patrol:KUMA")).not.toBe(first);
    memo.settle("quest:forest_patrol:ACE");
    expect(memo.requestIdFor("quest:forest_patrol:ACE")).not.toBe(first);
    for (let i = 0; i < 50; i++) expect(makeProgressionRequestId(Date.now() + i)).toMatch(PROGRESSION_REQUEST_ID);
    expect(makeProgressionRequestId(0, () => 0)).toMatch(PROGRESSION_REQUEST_ID);
  });
});

