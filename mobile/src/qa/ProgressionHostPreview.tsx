export const progressionHostPreviewScreens: Record<(typeof PROGRESSION_HOST_PREVIEW_ROUTES)[number], ComponentType> = {
  ProgressionQuests,
  ProgressionTraining,
  ProgressionMissions: missionsPreview(true),
  ProgressionMissionsPaused: missionsPreview(false),
};

